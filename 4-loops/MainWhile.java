// While é uma estrutura de repetição que executa um bloco de código enquanto uma condição for 
// verdadeira. A sintaxe básica é:
public class MainWhile {
    public static void main(String[] args) {
        int i = 0;
        while (i < 5) {
            System.out.println("i is: " + i);
            i++;
        }
    }
}