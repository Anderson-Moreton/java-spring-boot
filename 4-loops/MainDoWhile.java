// Do-While é uma estrutura de repetição que permite executar um bloco de código várias vezes, 
// com base em uma condição. A sintaxe básica do do-while é a seguinte:
public class MainDoWhile {
    public static void main(String[] args) {
        int i = 0;
        do {
            System.out.println("i is: " + i);
            i++;
        } while (i < 5);
    }
}