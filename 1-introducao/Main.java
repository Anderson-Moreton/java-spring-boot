// Variável
public class Main {
    public static void main(String[] args) {
        int farinha = 2;
        System.out.println("A receita requer " + farinha + " xícaras de farinha.");

        // Tipos primitivos
        byte idade = 25; // inteiro de 8 bits
        short anos = 2024; // inteiro de 16 bits
        int idade2 = 25; // inteiro
        long populacao = 7800000000L; // inteiro de 64 bits
        float peso = 70.5f; // ponto flutuante de 32 bits
        double altura = 1.75; // ponto flutuante
        boolean estudante = true; // booleano
        char genero = 'M'; // caractere

        System.out.println("Idade (byte): " + idade);
        System.out.println("Anos (short): " + anos);
        System.out.println("Idade (int): " + idade2);
        System.out.println("População (long): " + populacao);
        System.out.println("Peso (float): " + peso);
        System.out.println("Altura (double): " + altura);
        System.out.println("Estudante: " + estudante);
        System.out.println("Gênero: " + genero);
    }
}
