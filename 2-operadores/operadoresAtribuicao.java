// Operadores de Atribuição
public class operadoresAtribuicao {
    public static void main(String[] args) {
        int a = 10;
        int b = 5;

        // Operações de Atribuição
        a += b; // a = a + b
        System.out.println("a += b: " + a);

        a -= b; // a = a - b
        System.out.println("a -= b: " + a);

        a *= b; // a = a * b
        System.out.println("a *= b: " + a);

        a /= b; // a = a / b
        System.out.println("a /= b: " + a);

        a %= b; // a = a % b
        System.out.println("a %= b: " + a);
    }
}
