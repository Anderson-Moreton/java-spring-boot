public class operadoresAtribuicaoExercicio {
    public static void main(String[] args) {
        int numero = 5;

        // Operadores de Atribuição
        numero += 3; // número = número + 3
        System.out.println("Após += 3: " + numero);

        numero -= 2; // número = número - 2
        System.out.println("Após -= 2: " + numero);

        numero *= 4; // número = número * 4
        System.out.println("Após *= 4: " + numero);

        numero /= 2; // número = número / 2
        System.out.println("Após /= 2: " + numero); 

        System.out.println("Valor final: " + numero);
    }
}
