// Operadores Lógicos
public class operadoresLogicos {
    public static void main(String[] args) {
        boolean a = true;
        boolean b = false;

        // Operador AND (&&)
        System.out.println("a AND b: " + (a && b)); // false

        // Operador OR (||)
        System.out.println("a OR b: " + (a || b)); // true

        // Operador NOT (!)
        System.out.println("NOT a: " + (!a)); // false
        System.out.println("NOT b: " + (!b)); // true
    }
}
